const ATTRIBUTES = ['placeholder', 'title', 'aria-label'];

function translateValue(value: string): string {
  const exact = ZH_CN[value.trim()];
  if (exact) return value.replace(value.trim(), exact);
  return value
    .replace(/^([0-9]+) notes?$/, '$1 条笔记')
    .replace(/^([0-9]+) selected$/, '已选择 $1 项')
    .replace(/^Last edited (.+)$/, '最后编辑于 $1');
}

function translateNode(root: Node) {
  if (root.nodeType === Node.TEXT_NODE) {
    const text = root.textContent || '';
    const translated = translateValue(text);
    if (translated !== text) root.textContent = translated;
    return;
  }
  if (!(root instanceof Element)) return;
  if (root.matches('script, style, [contenteditable="true"], .material-symbols-outlined')) return;
  for (const attribute of ATTRIBUTES) {
    const value = root.getAttribute(attribute);
    if (!value) continue;
    const translated = translateValue(value);
    if (translated !== value) root.setAttribute(attribute, translated);
  }
  root.childNodes.forEach(translateNode);
}

export function startSimplifiedChineseLocalization(): () => void {
  document.documentElement.lang = 'zh-CN';
  translateNode(document.body);
  const observer = new MutationObserver(mutations => {
    for (const mutation of mutations) {
      if (mutation.type === 'characterData') translateNode(mutation.target);
      mutation.addedNodes.forEach(translateNode);
    }
  });
  observer.observe(document.body, { childList: true, subtree: true, characterData: true });
  return () => observer.disconnect();
}
